// Склонение нужно в двух мирах сразу: в браузере — для шапки всплывашки,
// в сборщике — для подписи под названием города в разметке пина. Поэтому файл
// лежит рядом с данными стран и не тянет за собой ничего лишнего.
export function pluralizeVacancies(count) {
  const mod100 = count % 100;
  const mod10 = count % 10;

  if (mod100 >= 11 && mod100 <= 14) {
    return 'вакансий';
  }
  if (mod10 === 1) {
    return 'вакансия';
  }
  if (mod10 >= 2 && mod10 <= 4) {
    return 'вакансии';
  }

  return 'вакансий';
}
